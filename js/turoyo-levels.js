  function toCy(tr) {
    var s = String(tr).toLowerCase()
      .replace(/š/g, 'sh').replace(/č/g, 'ch').replace(/ž/g, 'zh').replace(/ǧ/g, 'j').replace(/ġ/g, 'gh')
      .replace(/x/g, 'kh').replace(/ə/g, 'e')
      .normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[ʾʿ']/g, '');
    var pairs = [['kh', 'х'], ['sh', 'ш'], ['ch', 'ч'], ['zh', 'ж'], ['gh', 'г'],
      ['ya', 'я'], ['yu', 'ю'], ['yo', 'йо'], ['ye', 'е'], ['yi', 'йи'],
      ['a', 'а'], ['b', 'б'], ['v', 'в'], ['g', 'г'], ['d', 'д'], ['e', 'е'], ['z', 'з'], ['i', 'и'], ['y', 'й'], ['k', 'к'],
      ['l', 'л'], ['m', 'м'], ['n', 'н'], ['o', 'о'], ['p', 'п'], ['r', 'р'], ['s', 'с'], ['t', 'т'], ['u', 'у'], ['f', 'ф'],
      ['h', 'х'], ['q', 'к'], ['w', 'в'], ['j', 'дж']];
    var out = '';
    for (var i = 0; i < s.length;) {
      var hit = false;
      for (var j = 0; j < pairs.length; j++) {
        if (s.substr(i, pairs[j][0].length) === pairs[j][0]) { out += pairs[j][1]; i += pairs[j][0].length; hit = true; break; }
      }
      if (!hit) { out += s[i]; i++; }
    }
    return out;
  }
